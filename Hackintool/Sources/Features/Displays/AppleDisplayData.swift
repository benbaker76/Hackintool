import Foundation

struct AppleDisplayData {
	let displayGUID: UInt64?
	let displaySerial: UInt32?
	let usesCharPointer: Bool
	let vendorID: UInt32
	let productID: UInt32
	/// EDID bytes 8–17: vendor, product, serial, week and year.
	let serial: [UInt8]
	let chroma: [UInt8]
	let basicParams: [UInt8]
	/// An 18-byte monitor name descriptor (tag FC).
	let nameDescriptor: [UInt8]
	/// An 18-byte serial descriptor (tag FF), for displays that have one.
	let serialDescriptor: [UInt8]?
	let connectFlags: [UInt8]
	let capabilityString: String?
	let controllerID: [UInt8]?
	let firmwareLevel: [UInt8]?
	let mccsVersion: [UInt8]?
	let technologyType: [UInt8]?
	let appleSense: UInt32?
	let edid: [UInt8]

	/// Monitor range limits descriptor (tag FD) that fixes some displays: 56–76 Hz, 30–83 kHz, 170 MHz.
	static let monitorRanges: [UInt8] = [0x00, 0x00, 0x00, 0xfd, 0x00, 0x38, 0x4c, 0x1e, 0x53, 0x11, 0x00, 0x0a, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20]

	/// IOProviderMergeProperties presenting the display as this Apple display.
	func mergeProperties(name: String, edid: Data, displayClass: String, prefsKey: String?) -> [String: Any] {
		var properties: [String: Any] = [
			"DisplayProductName": name,
			"DisplayProductID": productID,
			"DisplayVendorID": vendorID,
			"IODisplayEDID": edid,
			"IODisplayConnectFlags": Data(connectFlags),
		]
		if let prefsKey = prefsKey {
			let folder = (prefsKey as NSString).deletingLastPathComponent
			properties["IODisplayPrefsKey"] = (folder as NSString).appendingPathComponent(String(format: "%@-%x-%x", displayClass, vendorID, productID))
		}
		if let appleSense = appleSense {
			properties["AppleDisplayType"] = 2
			properties["AppleSense"] = appleSense
		}
		if let guid = displayGUID {
			properties["IODisplayGUID"] = guid
		}
		if let serial = displaySerial {
			properties["DisplaySerialNumber"] = serial
		}
		if let capabilities = capabilityString {
			properties["IODisplayCapabilityString"] = capabilities.data(using: .ascii)
		}
		properties["IODisplayControllerID"] = controllerID.map { Data($0) }
		properties["IODisplayFirmwareLevel"] = firmwareLevel.map { Data($0) }
		properties["IODisplayMCCSVersion"] = mccsVersion.map { Data($0) }
		properties["IODisplayTechnologyType"] = technologyType.map { Data($0) }
		if usesCharPointer {
			properties["DisplayParameterHandlerUsesCharPtr"] = true
		}
		return properties
	}

